async (page) => {
  await page.goto(new URL(page.url()).origin+'/sprint-2');
  await page.getByRole('tab',{name:'05Episodios',exact:true}).click();
  const results=[];
  const check=(ok,name)=>{if(!ok) throw new Error(name);results.push(name);};
  const calendar=page.getByRole('region',{name:'Un mes, día a día',exact:true});
  const status=()=>calendar.getByRole('status').innerText();
  const select=async(label,value)=>page.getByRole('combobox',{name:label,exact:true}).selectOption(value);
  const dateButton=date=>calendar.locator(`[data-date="${date}"]`);
  const selected=()=>calendar.locator('[data-date][aria-pressed="true"]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-date')));
  const play=()=>calendar.getByRole('button',{name:'Reproducir',exact:true}).click();
  const pause=()=>calendar.getByRole('button',{name:'Pausar',exact:true}).click();
  const screenshot=name=>calendar.screenshot({path:`output/playwright/calendario_2026-10-23/${name}.png`,style:'body > header { visibility: hidden !important; }'});
  await select('Contaminante principal','PM10');await select('Año','ambos');await select('Periodo','12');
  check((await status()).includes('1 de Diciembre · Pausado'),'Inicio pausado');
  check((await calendar.innerText()).includes('Mala o peor: 15/31'),'PM10 diciembre 2023 15/31');
  check((await calendar.innerText()).includes('Mala o peor: 27/31'),'PM10 diciembre 2024 27/31');
  await dateButton('2024-12-31').click();
  check(JSON.stringify(await selected())===JSON.stringify(['2023-12-31','2024-12-31']),'Selección sincronizada');
  check((await dateButton('2024-12-31').getAttribute('style')).includes('background-color'),'Selección conserva el color');
  await screenshot('calendario_diciembre_pm10_escritorio');
  check(await page.getByRole('heading',{name:'Episodios consecutivos',exact:true}).count()===1,'Tablas históricas de episodios conservadas');
  await select('Contaminante principal','CO');
  check(await calendar.locator('[data-date^="2023-12-"][data-category="0"]').count()===31,'CO diciembre 2023 Buena 31/31');
  check(await calendar.locator('[data-date^="2024-12-"][data-category="0"]').count()===31,'CO diciembre 2024 Buena 31/31');
  check(await calendar.locator('[data-category="missing"]').count()===0,'Buena cero no se interpreta como ausencia');
  check((await calendar.innerText()).includes('Máximo diario del promedio móvil de 8 h'),'CO usa estadístico y unidad propios');
  await screenshot('calendario_diciembre_co_escritorio');
  await select('Periodo','2');
  check(await calendar.locator('[data-date^="2023-02-"]').count()===28,'Febrero 2023: 28 fechas reales');
  check(await calendar.locator('[data-date^="2024-02-"]').count()===29,'Febrero 2024: 29 fechas reales');
  check(await dateButton('2023-02-29').count()===0,'No se crea 29 febrero 2023');
  await dateButton('2024-02-29').click();
  check((await calendar.innerText()).includes('no tiene fecha equivalente en 2023'),'Día adicional explicado');
  check(JSON.stringify(await selected())===JSON.stringify(['2024-02-29']),'Solo fecha real seleccionada en día adicional');
  await screenshot('calendario_febrero29_escritorio');
  await select('Año','2024');await dateButton('2024-02-29').click();
  check((await calendar.innerText()).includes('no tiene fecha equivalente en 2023'),'Equivalencia explicada también al filtrar 2024');
  await select('Año','2023');
  check(await calendar.locator('[data-date]').count()===28,'Filtro 2023 no recorre fechas 2024');
  await select('Año','ambos');await select('Periodo','0');
  await select('Mes del calendario','2');
  check(await dateButton('2024-02-29').count()===1,'Todo el año ofrece mes explícito');
  await play();await select('Mes del calendario','1');await page.waitForTimeout(1600);
  check((await status()).includes('1 de Enero · Pausado'),'Mes explícito pausa y limpia temporizador');
  await select('Periodo','1');await select('Contaminante principal','O3');
  check(await calendar.locator('[data-date^="2023-01-"][data-category="missing"]').count()===31,'O3 enero 2023: 31 días sin indicador');
  check((await calendar.innerText()).includes('Máximo horario diario'),'O3 usa máximo horario, no promedio diario');
  await dateButton('2023-01-15').click();
  check((await calendar.locator('[aria-label="Detalle diario 2023"]').innerText()).includes('Lecturas utilizables: 0/24'),'Ausencia conserva conteos 0/24');
  await screenshot('calendario_ozono_sin_datos_escritorio');
  await dateButton('2023-01-01').click();await play();await page.waitForTimeout(1650);
  check((await selected()).some(d=>d.endsWith('-02')),'Reproducción avanza también por día sin datos');
  await pause();const paused=JSON.stringify(await selected());await page.waitForTimeout(1650);
  check(JSON.stringify(await selected())===paused,'Pausa detiene avance');
  await calendar.getByRole('button',{name:'Día siguiente →',exact:true}).focus();await page.keyboard.press('Enter');
  check((await selected()).some(d=>d.endsWith('-03')),'Avance con teclado Enter');
  await dateButton('2023-01-04').focus();await page.keyboard.press('Space');
  check((await selected()).some(d=>d.endsWith('-04')),'Seleccionar fecha con teclado Space');
  await play();await select('Contaminante principal','PM10');await page.waitForTimeout(1600);
  check((await status()).includes('1 de Enero · Pausado'),'Cambio de contaminante pausa');
  await play();await select('Año','2023');await page.waitForTimeout(1600);
  check((await status()).includes('1 de Enero · Pausado'),'Cambio de año pausa');
  await play();await select('Periodo','2');await page.waitForTimeout(1600);
  check((await status()).includes('1 de Febrero · Pausado'),'Cambio de periodo pausa');
  await dateButton('2023-02-27').click();await play();await page.waitForTimeout(3100);
  check((await status()).includes('28 de Febrero · Fin del mes'),'Recorrido 2023 termina el 28 y no reinicia');
  check(await calendar.getByRole('button',{name:'Reproducir',exact:true}).isDisabled(),'Reproducir desactivado al final');
  await select('Año','ambos');await dateButton('2024-02-28').click();await play();await page.waitForTimeout(3100);
  check((await status()).includes('29 de Febrero · Fin del mes'),'Recorrido comparativo termina el 29 y no pasa a marzo');
  await dateButton('2024-02-01').click();await play();await page.getByRole('tab',{name:'01Comparación mensual',exact:true}).click();await page.waitForTimeout(1600);
  check(await calendar.count()===0,'Abandonar episodios desmonta calendario');
  await page.getByRole('tab',{name:'05Episodios',exact:true}).click();
  check((await status()).includes('1 de Febrero · Pausado'),'Regreso a episodios inicia pausado');
  await play();await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(1650);
  check(await calendar.getByRole('button',{name:'Reproducir',exact:true}).isDisabled(),'Movimiento reducido desactiva reproducción');
  check((await status()).includes('Pausado'),'Activar movimiento reducido pausa');
  await calendar.getByRole('button',{name:'Día siguiente →',exact:true}).click();
  check((await selected()).some(d=>d.endsWith('-02')),'Movimiento reducido conserva controles manuales');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await dateButton('2024-02-29').click();await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth===window.innerWidth),'Móvil sin desbordamiento horizontal del documento');
  await screenshot('calendario_febrero29_movil');
  await select('Periodo','12');await select('Contaminante principal','PM10');await dateButton('2024-12-31').click();
  await screenshot('calendario_diciembre_pm10_movil');
  await page.setViewportSize({width:1440,height:1100});
  return {estado:'APROBADO',checks:results,capturas:6};
}
